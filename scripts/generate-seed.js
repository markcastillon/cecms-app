// Writes supabase/seed.sql from the same sample data demo mode uses.
// Run with: npm run seed
import fs from "node:fs";
import {
  SEED_ANNOUNCEMENTS,
  SEED_CENTERS,
  SEED_EVACUEES,
  SEED_FAMILIES,
  SEED_POLICIES,
  SEED_SUPPLIES,
  SEED_VOLUNTEERS,
} from "../src/data/seed.js";

const q = (v) => (typeof v === "number" || typeof v === "boolean" ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const ago = (minutes) => `now() - interval '${minutes} minutes'`;

function insert(table, columns, rows) {
  if (!rows.length) return "";
  const values = rows.map((r) => `  (${r.join(", ")})`).join(",\n");
  return `insert into public.${table} (${columns.join(", ")}) values\n${values}\non conflict do nothing;\n\n`;
}

let sql = `-- Sample data generated by scripts/generate-seed.js. All names are fictional.
-- Run after schema.sql in Supabase > SQL Editor. Safe to run again (existing rows are skipped).

`;

sql += insert("centers", ["id", "name", "location", "capacity", "status_override", "contact_person", "contact_number"],
  SEED_CENTERS.map((c) => [q(c.id), q(c.name), q(c.location), c.capacity, q(c.statusOverride), q(c.contactPerson), q(c.contactNumber)]));

sql += insert("families", ["id", "head_of_family", "purok", "contact_number", "center_id", "house_damage", "status", "registered_at"],
  SEED_FAMILIES.map((f) => [q(f.id), q(f.headOfFamily), q(f.purok), q(f.contactNumber), q(f.centerId), q(f.houseDamage), q(f.status), ago(f.minutesAgo)]));

sql += insert("evacuees", ["id", "family_id", "full_name", "age", "sex", "relationship", "vulnerable_group", "center_id", "status", "arrived_at"],
  SEED_EVACUEES.map((e) => [q(e.id), q(e.familyId), q(e.fullName), e.age, q(e.sex), q(e.relationship), q(e.vulnerableGroup), q(e.centerId), q(e.status), ago(e.minutesAgo)]));

sql += insert("announcements", ["id", "title", "message", "priority", "active", "posted_at"],
  SEED_ANNOUNCEMENTS.map((a) => [q(a.id), q(a.title), q(a.message), q(a.priority), a.active, ago(a.minutesAgo)]));

sql += insert("supplies", ["id", "center_id", "item", "unit", "quantity_received", "quantity_released", "updated_at"],
  SEED_SUPPLIES.map((s) => [q(s.id), q(s.centerId), q(s.item), q(s.unit), s.quantityReceived, s.quantityReleased, ago(s.minutesAgo)]));

sql += insert("volunteers", ["id", "full_name", "contact_number", "email", "availability", "skills", "preferred_center", "status", "submitted_at"],
  SEED_VOLUNTEERS.map((v) => [q(v.id), q(v.fullName), q(v.contactNumber), q(v.email), q(v.availability), q(v.skills), q(v.preferredCenter), q(v.status), ago(v.minutesAgo)]));

sql += insert("policies", ["id", "type", "title", "summary", "legal_basis", "status"],
  SEED_POLICIES.map((p) => [q(p.id), q(p.type), q(p.title), q(p.summary), q(p.legalBasis), q(p.status)]));

fs.writeFileSync(new URL("../supabase/seed.sql", import.meta.url), sql);
console.log(`Wrote supabase/seed.sql (${SEED_FAMILIES.length} families, ${SEED_EVACUEES.length} evacuees)`);
